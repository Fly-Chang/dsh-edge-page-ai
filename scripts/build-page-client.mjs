/**
 * 将页面客户端及其本地依赖打包为单个 ES 模块，供 Edge 薄壳扩展在隔离世界动态导入。
 * 入口: src/gateway/client/injected-page.mjs
 * 输出: src/edge-bridge/bridge-client.bundle.mjs（提交到仓库，扩展开发者模式直接加载）
 *
 * 只支持本项目使用的具名静态 import（无 default import / export）。
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = resolve(ROOT, 'src/gateway/client/injected-page.mjs');
const OUT = resolve(ROOT, 'src/edge-bridge/bridge-client.bundle.mjs');

const files = [];
const seen = new Set();

function addModule(file) {
  const normalized = resolve(file);
  if (seen.has(normalized)) {
    return;
  }
  seen.add(normalized);

  const source = readFileSync(normalized, 'utf8');
  const imports = [];
  const body = source.replace(
    /^import\s+\{([^}]*)\}\s+from\s+['"]([^'"]+)['"];\s*$/gm,
    (_match, _names, specifier) => {
      imports.push(resolve(dirname(normalized), specifier));
      return '';
    },
  );

  if (/^import\s/m.test(body)) {
    throw new Error(`unsupported import statement in ${normalized}`);
  }

  for (const dep of imports) {
    addModule(dep);
  }
  files.push({ file: normalized, body });
}

addModule(ENTRY);

mkdirSync(dirname(OUT), { recursive: true });
const output = [
  '// Generated by scripts/build-page-client.mjs. Do not edit directly.',
  ...files.map(({ file, body }) => `// === ${relative(ROOT, file)} ===\n${body}`),
].join('\n');

writeFileSync(OUT, `${output}\n`, 'utf8');
console.log(`[edge-page-ai] bundled ${files.length} modules -> ${relative(ROOT, OUT)}`);
